import { test } from 'node:test';
import assert from 'node:assert/strict';
import type { Work } from '../src/types.ts';
import { Identity } from '../src/identity.ts';
import { classify, parseArtTrack, type YtVideo } from '../src/ingest/classify.ts';
import { YouTubeClient, collectWork } from '../src/ingest/youtube.ts';

const ito: Work = {
  id: 'w-ito',
  title: '糸',
  original: ['中島みゆき'],
  lyricist: ['中島みゆき'],
  composer: ['中島みゆき'],
  year: 1992,
  genre: 'newmusic',
  intl: false,
};
const identity = new Identity([]);

const artTrack = (title: string, artist: string, composer: string, released = '2004-06-23') =>
  [
    'Provided to YouTube by Example Records',
    '',
    `${title} · ${artist}`,
    '',
    'Some Album',
    '',
    '℗ 2004 Example Records',
    '',
    `Released on: ${released}`,
    '',
    `Composer, Lyricist: ${composer}`,
    '',
    'Auto-generated by YouTube.',
  ].join('\n');

const video = (over: Partial<YtVideo>): YtVideo => ({
  id: 'v',
  title: '',
  description: '',
  channelId: 'c',
  channelTitle: 'someone',
  publishedAt: '2021-03-01T00:00:00Z',
  ...over,
});

test('Art Track の説明欄を構造化して読む', () => {
  const a = parseArtTrack(artTrack('糸', 'Bank Band', '中島みゆき'))!;
  assert.equal(a.title, '糸');
  assert.deepEqual(a.artists, ['Bank Band']);
  assert.deepEqual(a.composers, ['中島みゆき']);
  assert.deepEqual(a.lyricists, ['中島みゆき']);
  assert.equal(a.releasedOn, '2004-06-23');
});

test('クレジットが一致する Art Track はプロ層のカバー', () => {
  const d = classify(ito, video({ title: '糸', description: artTrack('糸', 'Bank Band', '中島みゆき'), channelTitle: 'Bank Band - Topic' }), identity);
  assert.deepEqual(d, { kind: 'cover', layer: 'art-track', artist: 'Bank Band', artistKind: 'pro', year: 2004, aiSuspect: false });
});

test('同名異曲はクレジットで弾く', () => {
  const d = classify(ito, video({ title: '糸', description: artTrack('糸', '別の歌手', '別の作曲家') }), identity);
  assert.deepEqual(d, { kind: 'reject', reason: 'different-work' });
});

test('原唱者本人の録音はセルフとして弾く', () => {
  const d = classify(ito, video({ title: '糸', description: artTrack('糸', '中島みゆき', '中島みゆき') }), identity);
  assert.deepEqual(d, { kind: 'reject', reason: 'self' });
});

test('一般投稿: 汎用タイトルは原唱者名の併記が必要', () => {
  const bare = classify(ito, video({ title: '糸 歌ってみた' }), identity);
  assert.deepEqual(bare, { kind: 'reject', reason: 'ambiguous-title' });
  const ok = classify(ito, video({ title: '【歌ってみた】糸 / 中島みゆき', channelTitle: 'うたうひと ch.', channelSubscribers: 5000 }), identity);
  assert.deepEqual(ok, { kind: 'cover', layer: 'ugc', artist: 'うたうひと', artistKind: 'amateur', year: 2021, aiSuspect: false });
});

test('一般投稿: カラオケ・反応動画・AI 歌声', () => {
  assert.equal((classify(ito, video({ title: '糸 中島みゆき カラオケ' }), identity) as { reason: string }).reason, 'instrumental');
  assert.equal((classify(ito, video({ title: '糸 中島みゆき リアクション cover' }), identity) as { reason: string }).reason, 'not-performance');
  const ai = classify(ito, video({ title: '糸 中島みゆき AI cover' }), identity);
  assert.equal(ai.kind === 'cover' && ai.aiSuspect, true);
});

test('YouTube Data API の収集パイプライン（モック）とクォータ計上', async () => {
  const responses: Record<string, unknown> = {
    search: { items: [{ id: { videoId: 'a' } }, { id: { videoId: 'b' } }, { id: { videoId: 'c' } }] },
    videos: {
      items: [
        { id: 'a', snippet: { title: '糸', description: artTrack('糸', 'Bank Band', '中島みゆき'), channelId: 'ca', channelTitle: 'Bank Band - Topic', publishedAt: '2004-06-23T00:00:00Z' }, statistics: { viewCount: '1000000' } },
        { id: 'b', snippet: { title: '糸 / 中島みゆき (cover)', description: '', channelId: 'cb', channelTitle: 'Singer Official', publishedAt: '2022-01-01T00:00:00Z' }, statistics: { viewCount: '5000' } },
        { id: 'c', snippet: { title: '糸 中島みゆき ピアノソロ', description: '', channelId: 'cc', channelTitle: 'piano', publishedAt: '2022-01-01T00:00:00Z' }, statistics: { viewCount: '9' } },
      ],
    },
    channels: { items: [{ id: 'cb', statistics: { subscriberCount: '250000' } }] },
  };
  const calls: string[] = [];
  const fakeFetch = (async (url: string | URL) => {
    const u = new URL(String(url));
    const endpoint = u.pathname.split('/').pop()!;
    calls.push(endpoint);
    assert.equal(u.searchParams.get('key'), 'TEST');
    return new Response(JSON.stringify(responses[endpoint]), { status: 200 });
  }) as typeof fetch;
  const yt = new YouTubeClient('TEST', fakeFetch);
  const { covers, stats } = await collectWork(ito, yt, identity);
  assert.equal(stats.candidates, 3);
  assert.deepEqual(stats.rejected, { instrumental: 1 });
  assert.deepEqual(
    covers.map((c) => [c.artist, c.kind, c.via, c.year]),
    [
      ['Bank Band', 'pro', 'youtube-art-track', 2004],
      ['Singer', 'net', 'youtube-ugc', 2022],
    ],
  );
  // search 3 クエリ × 100 + videos 1 + channels 1
  assert.equal(yt.quotaUsed, 302);
  assert.equal(calls.filter((c) => c === 'search').length, 3);
});
